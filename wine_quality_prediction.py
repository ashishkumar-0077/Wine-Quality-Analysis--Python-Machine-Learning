import numpy as np
import pandas as pd
from sklearn.model_selection import train_test_split
import matplotlib.pyplot as plt
import seaborn as sns
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import accuracy_score,confusion_matrix,classification_report

# Loading Dataset
df = pd.read_csv("winequality-red.csv")

# Show First 5 Rows
df.head()

# Rows And Columns in the Dataset
df.shape

# Checking Missing VAlues
df.isnull().sum()

"""Data Analysis and Visulization"""

# Statistical Measure
df.describe()

import warnings
warnings.filterwarnings("ignore")

# Number of Values for Each Qualities
sns.catplot(x="quality",data=df,kind="count",palette=["red", "blue", "green", "orange"])

# Vola Acidity vs Quality
plt.figure(figsize=(5,5))
sns.barplot(x="quality",y="volatile acidity",data=df,palette=["red", "blue", "green", "orange"])

# citric acid vs quality
plt.figure(figsize=(5,5))
sns.barplot(x="quality",y="citric acid",data=df,palette=["red", "blue", "green", "orange"])

"""Correlation

1. Positive Correlation
2. Negative Correlation
"""

correlation = df.corr()

# Constructing a heatmap to understand the relationship between columns
plt.figure(figsize=(10,10))
sns.heatmap(correlation,cbar=True,square=True,fmt=".1f",annot=True,annot_kws={"size":8},cmap="Blues")

"""Data Processing"""

# Separate the data and Label
X = df.drop("quality", axis=1)
print(X)

"""Label Binarization"""

Y = df["quality"].apply(lambda y_value: 1 if y_value>=7 else 0)
print(Y)

"""Train Test Split"""

X_train, X_test, Y_train, Y_test = train_test_split(X, Y, test_size=0.2, random_state=3)

print(Y.shape, Y_train.shape, Y_test.shape)

"""Model Training:

RandomForestClassifier
"""

model = RandomForestClassifier()

model.fit(X_train, Y_train)

"""Model Evalution

Accuracy Score
"""

# Accuracy on Test data
X_test_prediction = model.predict(X_test)
test_data_accuracy = accuracy_score(X_test_prediction, Y_test)

print("Accuracy : ",test_data_accuracy)

"""Building A Predictive System"""

input_data = (7.8,0.88,0.0,2.6,0.098,25.0,67.0,0.9968,3.2,0.68,9.8)

# Changing the input data into numpy array
input_data_as_numpy_array = np.asarray(input_data)

# Reshape the data as we are predicting the label for only one instance
input_data_reshaped = input_data_as_numpy_array.reshape(1,-1)

prediction = model.predict(input_data_reshaped)
print(prediction)

if (prediction[0]==1):
    print("Good Quality Wine")
else:
    print("Bad Quality Wine")

